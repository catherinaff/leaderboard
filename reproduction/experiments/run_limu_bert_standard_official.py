def parse_args(argv: list[str] | None = None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--datasets", nargs="+", default=["uci_har"], choices=["uci_har", *PROCESSED_DATASETS])
    parser.add_argument("--seeds", nargs="+", type=int, default=SEEDS)
    parser.add_argument("--pretrain-epochs", type=int, default=200)
    parser.add_argument("--classifier-epochs", type=int, default=200)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--patience", type=int, default=25)
    parser.add_argument("--min-delta", type=float, default=5e-4)
    parser.add_argument("--grad-clip", type=float, default=1.0)
    parser.add_argument("--val-ratio", type=float, default=0.1)
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--log-every", type=int, default=10)
    parser.add_argument("--run-tag", default="uci_har_limu_bert_standard_official")
    parser.add_argument("--merge", action="store_true")
    parser.add_argument("--save-checkpoints", action="store_true")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    for dataset in args.datasets:
        if dataset == "uci_har":
            run_uci_har(args)
        else:
            run_processed_standard(dataset, args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
