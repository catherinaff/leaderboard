def load_benchmark(benchmark_id: str) -> dict:
    path = BENCHMARKS_DIR / f"{benchmark_id}.json"
    if not path.is_file():
        raise SystemExit(f"Missing benchmark definition: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def import_official():
    if not OFFICIAL_REPO.is_dir():
        raise SystemExit(f"Missing official LIMU-BERT repository: {OFFICIAL_REPO}")
    if str(OFFICIAL_REPO) not in sys.path:
        sys.path.insert(0, str(OFFICIAL_REPO))
    from config import MaskConfig, load_model_config
    from models import LIMUBertModel4Pretrain, fetch_classifier
    from utils import Preprocess4Mask

    return MaskConfig, load_model_config, LIMUBertModel4Pretrain, fetch_classifier, Preprocess4Mask


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def official_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=OFFICIAL_REPO,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except Exception:
        return OFFICIAL_COMMIT_FALLBACK


def seed_all(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def metric_bundle(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    return {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "f1_macro": float(f1_score(y_true, y_pred, average="macro", zero_division=0)),
        "f1_weighted": float(f1_score(y_true, y_pred, average="weighted", zero_division=0)),
    }


def load_uci_har() -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, dict]:
    data_dir = DATASETS_DIR / "uci_har" / "UCI HAR Dataset"
    if not (data_dir / "train" / "Inertial Signals").is_dir():
        raise SystemExit("UCI-HAR data missing. Run experiments/download_uci_har.py first.")

    xs, ys, subjects, train_masks = [], [], [], []
    for split, is_train in (("train", True), ("test", False)):
        sig_dir = data_dir / split / "Inertial Signals"
        arrays = [np.loadtxt(sig_dir / f"{name}_{split}.txt", dtype=np.float32) for name in UCI_SIGNALS]
        x_split = np.stack(arrays, axis=2)
        y_split = np.loadtxt(data_dir / split / f"y_{split}.txt", dtype=np.int64) - 1
        s_split = np.loadtxt(data_dir / split / f"subject_{split}.txt", dtype=np.int64)
        xs.append(x_split)
        ys.append(y_split)
        subjects.append(s_split)
        train_masks.append(np.full(len(y_split), is_train, dtype=bool))

    meta = {
        "split": "official_fixed",
        "train_subjects": "UCI-HAR official train split",
        "test_subjects": "UCI-HAR official test split",
        "original_shape": [int(sum(len(a) for a in xs)), 128, 9],
    }
    return (
        np.concatenate(xs).astype(np.float32),
        np.concatenate(ys).astype(np.int64),
        np.concatenate(subjects).astype(np.int64),
        np.concatenate(train_masks),
        meta,
    )


def load_processed(benchmark_id: str) -> tuple[np.ndarray, np.ndarray, np.ndarray, dict]:
    path = DATASETS_DIR / "processed" / f"{benchmark_id}_windows.npz"
    if not path.is_file():
        raise SystemExit(f"Processed data missing for {benchmark_id}: {path}")
    data = np.load(path, allow_pickle=True)
    meta = json.loads(str(data["meta"])) if "meta" in data.files else {}
    meta.update(
        {
            "processed_path": str(path.relative_to(ROOT)),
            "original_shape": [int(v) for v in data["x"].shape],
            "label_names": [str(v) for v in data["label_names"].tolist()] if "label_names" in data.files else [],
            "channel_names": [str(v) for v in data["channel_names"].tolist()] if "channel_names" in data.files else [],
        }
    )
    return (
        np.asarray(data["x"], dtype=np.float32),
        np.asarray(data["y"], dtype=np.int64),
        np.asarray(data["subjects"], dtype=np.int64),
        meta,
    )


def fixed_subject_mask(subjects: np.ndarray, meta: dict) -> tuple[np.ndarray, np.ndarray]:
    train_subjects = {int(v) for v in meta.get("train_subjects", [])}
    test_subjects = {int(v) for v in meta.get("test_subjects", [])}
    if not train_subjects or not test_subjects:
        raise SystemExit("Fixed subject split requires train_subjects/test_subjects in processed metadata.")
    return np.isin(subjects, sorted(train_subjects)), np.isin(subjects, sorted(test_subjects))


def standard_splits(benchmark_id: str, subjects: np.ndarray, meta: dict) -> list[dict]:
    bench = load_benchmark(benchmark_id)
    protocol = bench.get("protocol", {})
    protocol_type = str(protocol.get("type", "")).lower()
    if "fixed" in protocol_type:
        train_idx, test_idx = fixed_subject_mask(subjects, meta)
        return [
            {
                "name": "fixed_subject_split",
                "train_idx": train_idx,
                "test_idx": test_idx,
                "train_subjects": sorted({int(v) for v in subjects[train_idx]}),
                "test_subjects": sorted({int(v) for v in subjects[test_idx]}),
            }
        ]
    if "loso" not in protocol_type and "leave-one-subject-out" not in protocol_type:
        raise SystemExit(f"Unsupported Standard split for {benchmark_id}: {protocol.get('type')}")
    splits = []
    for subject in sorted({int(v) for v in subjects}):
        test_idx = subjects == subject
        train_idx = subjects != subject
        splits.append(
            {
                "name": f"loso_subject_{subject}",
                "train_idx": train_idx,
                "test_idx": test_idx,
                "test_subject": subject,
                "train_subjects": sorted({int(v) for v in subjects[train_idx]}),
                "test_subjects": [subject],
            }
        )
    return splits


def resample_length(x: np.ndarray, target_len: int = 120) -> np.ndarray:
    if x.shape[1] == target_len:
        return x.astype(np.float32)
    old_t = np.linspace(0.0, 1.0, x.shape[1], dtype=np.float32)
    new_t = np.linspace(0.0, 1.0, target_len, dtype=np.float32)
    out = np.empty((x.shape[0], target_len, x.shape[2]), dtype=np.float32)
    for c in range(x.shape[2]):
        out[:, :, c] = np.apply_along_axis(lambda row: np.interp(new_t, old_t, row), 1, x[:, :, c])
    return out


def adapt_limu_channels(x: np.ndarray) -> tuple[np.ndarray, str]:
    if x.shape[2] == 6:
        return x.astype(np.float32), "native_6ch"
    if x.shape[2] > 6:
        return x[:, :, :6].astype(np.float32), f"first6_of_{x.shape[2]}ch"
    pad = np.zeros((x.shape[0], x.shape[1], 6 - x.shape[2]), dtype=np.float32)
    return np.concatenate([x, pad], axis=2).astype(np.float32), f"zero_padded_{x.shape[2]}ch_to_6ch"


def stratified_train_val(train_mask: np.ndarray, y: np.ndarray, seed: int, val_ratio: float) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    train_idx = np.zeros_like(train_mask, dtype=bool)
    val_idx = np.zeros_like(train_mask, dtype=bool)
    for label in np.unique(y[train_mask]):
        positions = np.flatnonzero(train_mask & (y == label))
        rng.shuffle(positions)
        val_count = max(1, int(round(len(positions) * val_ratio)))
        if val_count >= len(positions):
            val_count = max(1, len(positions) - 1)
        val_idx[positions[:val_count]] = True
        train_idx[positions[val_count:]] = True
    return train_idx, val_idx


def normalize_train_only(x: np.ndarray, train_idx: np.ndarray) -> tuple[np.ndarray, dict]:
    mean = x[train_idx].mean(axis=(0, 1), keepdims=True)
    std = x[train_idx].std(axis=(0, 1), keepdims=True) + 1e-6
    x_norm = ((x - mean) / std).astype(np.float32)
    return x_norm, {
        "type": "channel_zscore",
        "fit": "train_windows_only",
        "mean": mean.reshape(-1).astype(float).tolist(),
        "std": std.reshape(-1).astype(float).tolist(),
    }


class MaskedDataset(Dataset):
    def __init__(self, x: np.ndarray, mask_cfg):
        _, _, _, _, Preprocess4Mask = import_official()
        self.x = x
        self.masker = Preprocess4Mask(mask_cfg)

    def __len__(self) -> int:
        return len(self.x)

    def __getitem__(self, index: int):
        mask_seq, masked_pos, seq = self.masker(self.x[index])
        return torch.from_numpy(mask_seq).float(), torch.from_numpy(masked_pos).long(), torch.from_numpy(seq).float()


def make_loader(x: np.ndarray, y: np.ndarray, idx: np.ndarray, batch_size: int, shuffle: bool) -> DataLoader:
    return DataLoader(
        TensorDataset(torch.from_numpy(x[idx]).float(), torch.from_numpy(y[idx]).long()),
        batch_size=batch_size,
        shuffle=shuffle,
        drop_last=False,
    )


def pretrain_transformer(x: np.ndarray, train_idx: np.ndarray, val_idx: np.ndarray, args, seed: int, device: torch.device):
    MaskConfig, load_model_config, LIMUBertModel4Pretrain, _, _ = import_official()
    model_cfg = load_model_config("pretrain_base", "base", "v1")
    mask_cfg = MaskConfig.from_json(str(OFFICIAL_REPO / "config" / "mask.json"))
    model = LIMUBertModel4Pretrain(model_cfg).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
    criterion = nn.MSELoss(reduction="none")
    train_loader = DataLoader(MaskedDataset(x[train_idx], mask_cfg), batch_size=args.batch_size, shuffle=True)
    val_loader = DataLoader(MaskedDataset(x[val_idx], mask_cfg), batch_size=args.batch_size, shuffle=False)

    best_state = copy.deepcopy(model.state_dict())
    best_loss = float("inf")
    stale = 0
    epochs_run = 0
    for epoch in range(1, args.pretrain_epochs + 1):
        model.train()
        losses = []
        for mask_seq, masked_pos, seq in train_loader:
            mask_seq = mask_seq.to(device)
            masked_pos = masked_pos.to(device)
            seq = seq.to(device)
            optimizer.zero_grad(set_to_none=True)
            recon = model(mask_seq, masked_pos)
            loss = criterion(recon, seq).mean()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
            optimizer.step()
            losses.append(float(loss.detach().cpu()))

        model.eval()
        val_losses = []
        with torch.no_grad():
            for mask_seq, masked_pos, seq in val_loader:
                mask_seq = mask_seq.to(device)
                masked_pos = masked_pos.to(device)
                seq = seq.to(device)
                val_losses.append(float(criterion(model(mask_seq, masked_pos), seq).mean().detach().cpu()))
        val_loss = float(np.mean(val_losses))
        epochs_run = epoch
        if epoch == 1 or epoch % args.log_every == 0:
            print(f"seed={seed} pretrain epoch={epoch} loss={np.mean(losses):.5f} val_loss={val_loss:.5f}", flush=True)
        if val_loss < best_loss - args.min_delta:
            best_loss = val_loss
            best_state = copy.deepcopy(model.state_dict())
            stale = 0
        else:
            stale += 1
            if stale >= args.patience:
                print(f"seed={seed} pretrain early_stop epoch={epoch}", flush=True)
                break
    model.load_state_dict(best_state)
    return model, {"pretrain_epochs_run": epochs_run, "pretrain_best_val_loss": best_loss}


def generate_embeddings(pretrain_model, x: np.ndarray, args, device: torch.device) -> np.ndarray:
    _, load_model_config, LIMUBertModel4Pretrain, _, _ = import_official()
    model_cfg = load_model_config("pretrain_base", "base", "v1")
    embedder = LIMUBertModel4Pretrain(model_cfg, output_embed=True).to(device)
    embedder.load_state_dict(pretrain_model.state_dict())
    embedder.eval()
    loader = DataLoader(TensorDataset(torch.from_numpy(x).float()), batch_size=args.batch_size, shuffle=False)
    outputs = []
    with torch.no_grad():
        for (xb,) in loader:
            outputs.append(embedder(xb.to(device)).detach().cpu().numpy())
    return np.concatenate(outputs).astype(np.float32)


def expand_chunks(embeddings: np.ndarray, y: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    n, seq_len, hidden = embeddings.shape
    chunk_len = 20
    if seq_len % chunk_len != 0:
        raise SystemExit(f"Embedding sequence length {seq_len} is not divisible by {chunk_len}")
    chunks_per_window = seq_len // chunk_len
    x_chunks = embeddings.reshape(n * chunks_per_window, chunk_len, hidden)
    y_chunks = np.repeat(y, chunks_per_window)
    groups = np.repeat(np.arange(n), chunks_per_window)
    return x_chunks.astype(np.float32), y_chunks.astype(np.int64), groups.astype(np.int64)


def aggregate_window_predictions(logits: np.ndarray, groups: np.ndarray, window_ids: np.ndarray) -> np.ndarray:
    preds = []
    for wid in window_ids:
        probs = torch.softmax(torch.from_numpy(logits[groups == wid]), dim=1).numpy()
        preds.append(int(probs.mean(axis=0).argmax()))
    return np.asarray(preds, dtype=np.int64)


def eval_classifier(model, loader: DataLoader, device: torch.device) -> tuple[np.ndarray, np.ndarray]:
    model.eval()
    logits, labels = [], []
    with torch.no_grad():
        for xb, yb in loader:
            out = model(xb.to(device), False)
            logits.append(out.detach().cpu().numpy())
            labels.append(yb.numpy())
    return np.concatenate(logits), np.concatenate(labels)


def train_classifier(
    embeddings: np.ndarray,
    y: np.ndarray,
    train_idx: np.ndarray,
    val_idx: np.ndarray,
    test_idx: np.ndarray,
    args,
    seed: int,
    device: torch.device,
    monitor_metric: str = "accuracy",
):
    _, load_model_config, _, fetch_classifier, _ = import_official()
    x_chunks, y_chunks, groups = expand_chunks(embeddings, y)
    train_chunk_idx = np.isin(groups, np.flatnonzero(train_idx))
    val_chunk_idx = np.isin(groups, np.flatnonzero(val_idx))
    test_chunk_idx = np.isin(groups, np.flatnonzero(test_idx))
    train_loader = make_loader(x_chunks, y_chunks, train_chunk_idx, args.batch_size, True)
    val_loader = make_loader(x_chunks, y_chunks, val_chunk_idx, args.batch_size, False)
    test_loader = make_loader(x_chunks, y_chunks, test_chunk_idx, args.batch_size, False)

    model_cfg = load_model_config("classifier_base_gru", "gru", "v2")
    model = fetch_classifier("gru", model_cfg, input=x_chunks.shape[-1], output=int(y.max() + 1)).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
    criterion = nn.CrossEntropyLoss()
    best_state = copy.deepcopy(model.state_dict())
    best_val = -1.0
    stale = 0
    epochs_run = 0
    for epoch in range(1, args.classifier_epochs + 1):
        model.train()
        losses = []
        for xb, yb in train_loader:
            xb = xb.to(device)
            yb = yb.to(device)
            optimizer.zero_grad(set_to_none=True)
            loss = criterion(model(xb, True), yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
            optimizer.step()
            losses.append(float(loss.detach().cpu()))
        val_logits, _ = eval_classifier(model, val_loader, device)
        val_windows = np.flatnonzero(val_idx)
        val_pred = aggregate_window_predictions(val_logits, groups[val_chunk_idx], val_windows)
        val_metric = metric_bundle(y[val_windows], val_pred)[monitor_metric]
        epochs_run = epoch
        if epoch == 1 or epoch % args.log_every == 0:
            print(f"seed={seed} classifier epoch={epoch} loss={np.mean(losses):.5f} val_{monitor_metric}={val_metric:.5f}", flush=True)
        if val_metric > best_val + args.min_delta:
            best_val = val_metric
            best_state = copy.deepcopy(model.state_dict())
            stale = 0
        else:
            stale += 1
            if stale >= args.patience:
                print(f"seed={seed} classifier early_stop epoch={epoch}", flush=True)
                break

    model.load_state_dict(best_state)
    train_logits, _ = eval_classifier(model, make_loader(x_chunks, y_chunks, train_chunk_idx, args.batch_size, False), device)
    val_logits, _ = eval_classifier(model, val_loader, device)
    test_logits, _ = eval_classifier(model, test_loader, device)
    train_windows = np.flatnonzero(train_idx)
    val_windows = np.flatnonzero(val_idx)
    test_windows = np.flatnonzero(test_idx)
    train_pred = aggregate_window_predictions(train_logits, groups[train_chunk_idx], train_windows)
    val_pred = aggregate_window_predictions(val_logits, groups[val_chunk_idx], val_windows)
    test_pred = aggregate_window_predictions(test_logits, groups[test_chunk_idx], test_windows)
    return {
        "classifier_epochs_run": epochs_run,
        f"classifier_best_val_{monitor_metric}": best_val,
        "train": metric_bundle(y[train_windows], train_pred),
        "validation": metric_bundle(y[val_windows], val_pred),
        "test": metric_bundle(y[test_windows], test_pred),
    }, model


def summarize(seed_rows: list[dict]) -> dict:
    keys = sorted(seed_rows[0]["test"])
    out = {}
    for key in keys:
        vals = np.asarray([row["test"][key] for row in seed_rows], dtype=np.float64)
        out[key] = float(vals.mean())
        out[f"{key}_std"] = float(vals.std(ddof=0))
    return out


